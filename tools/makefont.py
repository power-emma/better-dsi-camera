# Generates source/font.c from a TTF. Needs Pillow.
# python3 tools/makefont.py /usr/share/fonts/noto/NotoSans-Medium.ttf 12 > source/font.c

import sys
from PIL import Image, ImageDraw, ImageFont

path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
height = ascent + descent

glyphs = []
for c in range(32, 127):
    ch = chr(c)
    img = Image.new("L", (round(font.getlength(ch)), height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    glyphs.append(img)

# Crop rows no glyph uses.
top = min(g.getbbox()[1] for g in glyphs if g.getbbox())
bottom = max(g.getbbox()[3] for g in glyphs if g.getbbox())
height = bottom - top

widths, offsets, data = [], [], []
for g in glyphs:
    widths.append(g.width)
    offsets.append(len(data))
    data.extend(g.crop((0, top, g.width, bottom)).tobytes())

print("// Generated by tools/makefont.py from %s at %dpx." % (path.split("/")[-1], size))
print('#include "font.h"\n')
print("const int fontHeight = %d;\n" % height)
print("const unsigned char fontWidth[95] = {%s};\n" % ", ".join(map(str, widths)))
print("const unsigned short fontOffset[95] = {%s};\n" % ", ".join(map(str, offsets)))
print("// 8-bit coverage, row by row")
print("const unsigned char fontData[%d] = {" % len(data))
for i in range(0, len(data), 24):
    print("    " + ", ".join(map(str, data[i:i + 24])) + ",")
print("};")
